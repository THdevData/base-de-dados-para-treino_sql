CREATE SCHEMA sales;

CREATE TABLE sales.departments (
    department_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE sales.employees (
    employee_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_id INTEGER NOT NULL REFERENCES sales.departments(department_id),
    full_name VARCHAR(150) NOT NULL,
    email VARCHAR(254) NOT NULL UNIQUE,
    hire_date DATE NOT NULL,
    salary NUMERIC(12, 2) NOT NULL CHECK (salary > 0),
    active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE sales.customers (
    customer_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_name VARCHAR(160) NOT NULL,
    contact_name VARCHAR(150),
    email VARCHAR(254),
    phone VARCHAR(30),
    city VARCHAR(100) NOT NULL,
    state CHAR(2) NOT NULL,
    created_at DATE NOT NULL DEFAULT CURRENT_DATE
);

CREATE UNIQUE INDEX customers_email_lower_uq
    ON sales.customers (LOWER(email))
    WHERE email IS NOT NULL;

CREATE TABLE sales.categories (
    category_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE sales.products (
    product_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id INTEGER NOT NULL REFERENCES sales.categories(category_id),
    sku VARCHAR(40) NOT NULL UNIQUE,
    name VARCHAR(160) NOT NULL,
    unit_price NUMERIC(12, 2) NOT NULL CHECK (unit_price > 0),
    active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE sales.orders (
    order_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id INTEGER NOT NULL REFERENCES sales.customers(customer_id),
    employee_id INTEGER NOT NULL REFERENCES sales.employees(employee_id),
    order_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status VARCHAR(20) NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'confirmed', 'shipped', 'cancelled')),
    discount_percent NUMERIC(5, 2) NOT NULL DEFAULT 0
        CHECK (discount_percent >= 0 AND discount_percent <= 100)
);

CREATE TABLE sales.order_items (
    order_item_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id INTEGER NOT NULL REFERENCES sales.orders(order_id),
    product_id INTEGER NOT NULL REFERENCES sales.products(product_id),
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    unit_price NUMERIC(12, 2) NOT NULL CHECK (unit_price > 0),
    UNIQUE (order_id, product_id)
);

CREATE TABLE sales.payments (
    payment_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id INTEGER NOT NULL REFERENCES sales.orders(order_id),
    payment_date TIMESTAMP,
    amount NUMERIC(12, 2) NOT NULL CHECK (amount > 0),
    method VARCHAR(20) NOT NULL
        CHECK (method IN ('pix', 'credit_card', 'bank_transfer', 'boleto')),
    status VARCHAR(20) NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'paid', 'failed', 'cancelled')),
    CHECK ((status = 'paid') = (payment_date IS NOT NULL))
);

CREATE INDEX employees_department_idx ON sales.employees (department_id);
CREATE INDEX products_category_idx ON sales.products (category_id);
CREATE INDEX orders_customer_date_idx ON sales.orders (customer_id, order_date DESC);
CREATE INDEX orders_employee_date_idx ON sales.orders (employee_id, order_date DESC);
CREATE INDEX orders_status_date_idx ON sales.orders (status, order_date);
CREATE INDEX order_items_product_idx ON sales.order_items (product_id);
CREATE INDEX payments_order_status_idx ON sales.payments (order_id, status);
CREATE INDEX payments_paid_date_idx ON sales.payments (payment_date)
    WHERE status = 'paid';

CREATE VIEW sales.v_order_summary AS
WITH item_totals AS (
    SELECT
        order_id,
        SUM(quantity * unit_price) AS subtotal
    FROM sales.order_items
    GROUP BY order_id
),
payment_totals AS (
    SELECT
        order_id,
        SUM(amount) FILTER (WHERE status = 'paid') AS amount_paid
    FROM sales.payments
    GROUP BY order_id
)
SELECT
    o.order_id,
    o.customer_id,
    o.employee_id,
    o.order_date,
    o.status,
    COALESCE(i.subtotal, 0)::NUMERIC(12, 2) AS subtotal,
    o.discount_percent,
    (COALESCE(i.subtotal, 0) * (1 - o.discount_percent / 100))::NUMERIC(12, 2)
        AS total_amount,
    COALESCE(p.amount_paid, 0)::NUMERIC(12, 2) AS amount_paid,
    (
        COALESCE(i.subtotal, 0) * (1 - o.discount_percent / 100)
        - COALESCE(p.amount_paid, 0)
    )::NUMERIC(12, 2) AS balance_due
FROM sales.orders AS o
LEFT JOIN item_totals AS i ON i.order_id = o.order_id
LEFT JOIN payment_totals AS p ON p.order_id = o.order_id;
